    if dong in tier_2024.index:
        t = tier_2024.loc[dong, '상권티어']
        q = tier_2024.loc[dong, '복합점수_분위']
        matched.append({'상권명': row['상권명'], '대표_행정동': dong,
                        '상권티어': t, '2024_분위': round(q, 3)})

