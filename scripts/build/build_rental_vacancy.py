# ── 1. 원본 로딩 (3행 헤더 무시) ──────────────────────────────────
raw = pd.read_csv(SRC, header=None, skiprows=3, encoding='utf-8-sig')

YEARS   = [2020, 2021, 2022, 2023, 2024, 2025]
METRICS = ['임대료', '공실률', '투자수익률', '소득수익률', '자본수익률']

cols = ['지역_대분류', '상권명']
for y in YEARS:
    for m in METRICS:
        cols.append(f'{y}_{m}')
raw.columns = cols

# ── 2. 상권명 정리 ─────────────────────────────────────────────────
# "002001 광화문" → "광화문",  "003 강남지역" → "강남지역"
for c in ['지역_대분류', '상권명']:
    raw[c] = raw[c].astype(str).str.strip('"').str.replace(r'^\d+\s+', '', regex=True).str.strip()

# 소계(지역 집계) 행 제거
raw = raw[raw['상권명'] != '소계'].copy()
raw = raw[raw['상권명'] != '서울'].copy()

# ── 3. Wide → Long ─────────────────────────────────────────────────
value_cols = [c for c in raw.columns if c not in ['지역_대분류', '상권명']]
long = raw.melt(id_vars=['지역_대분류', '상권명'],
                value_vars=value_cols,
                var_name='연도_지표', value_name='값')

long[['연도', '지표']] = long['연도_지표'].str.extract(r'^(\d{4})_(.+)$')
long.drop(columns='연도_지표', inplace=True)
long['연도'] = long['연도'].astype(int)
long['값']   = pd.to_numeric(long['값'].replace('-', np.nan), errors='coerce')

# Long → 피벗 (행: 상권×연도, 열: 5개 지표)
clean = long.pivot_table(index=['지역_대분류', '상권명', '연도'],
                          columns='지표', values='값').reset_index()
clean.columns.name = None
clean = clean[['지역_대분류', '상권명', '연도'] + METRICS]
clean = clean.sort_values(['상권명', '연도']).reset_index(drop=True)

# ── 4. 저장: tidy 데이터 ──────────────────────────────────────────
clean.to_csv('data/main_data/임대료_공실률.csv', index=False, encoding='utf-8-sig')
print(f"저장: data/임대료_공실률.csv  ({len(clean)}행, {clean['상권명'].nunique()}개 상권)")
print(f"      연도 범위: {clean['연도'].min()}~{clean['연도'].max()}")

